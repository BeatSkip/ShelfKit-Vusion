def _parse(art: str) -> list[str]:
    rows = [r for r in art.strip("\n").splitlines()]
    if len(rows) != BASE or any(len(r) != BASE for r in rows):
        raise ValueError("an icon must be 12 rows of 12 characters")
    return rows


ICONS: dict[str, list[str]] = {name: _parse(art) for name, art in _ART.items()}


def names() -> list[str]:
    return sorted(ICONS)


def sizes() -> list[int]:
    return [BASE * k for k in (1, 2, 3, 4)]


def pixels(name: str, size: int):
    """(x, y) of every ink pixel at this size (a whole multiple of 12)."""
    k = max(1, size // BASE)
    for y, row in enumerate(ICONS[name]):
        for x, ch in enumerate(row):
            if ch == "#":
                for dy in range(k):
                    for dx in range(k):
                        yield x * k + dx, y * k + dy
