def _parse(art, size: int, inks: str) -> list[str]:
    rows = art if isinstance(art, list) else [r for r in art.strip("\n").splitlines()]
    if len(rows) != size or any(len(r) != size for r in rows):
        raise ValueError(f"an icon must be {size} rows of {size} characters")
    if any(ch not in inks + "." for r in rows for ch in r):
        raise ValueError(f"an icon uses only {inks} and .")
    return rows


ICONS: dict[str, list[str]] = {name: _parse(art, BASE, "#") for name, art in _ART.items()}
ICONS.update({name: _parse(art, BIG, "#rw") for name, art in _BIG.items()})


def names() -> list[str]:
    return sorted(ICONS)


def small_names() -> list[str]:
    return sorted(n for n in ICONS if len(ICONS[n]) == BASE)


def big_names() -> list[str]:
    return sorted(n for n in ICONS if len(ICONS[n]) != BASE)


def base(name: str) -> int:
    """The grid an icon is drawn on: 12, or 32 for a big- picture."""
    return len(ICONS[name]) if name in ICONS else BASE


def sizes(name: str | None = None) -> list[int]:
    b = base(name) if name else BASE
    return [b * k for k in ((1, 2, 3, 4) if b == BASE else (1, 2, 3))]


def pixels(name: str, size: int):
    """(x, y, ink) of every drawn pixel at this size (a whole multiple of the icon's grid);
    ink is '#' (black, or the icon's colour), 'r' (red) or 'w' (white)."""
    k = max(1, size // base(name))
    for y, row in enumerate(ICONS[name]):
        for x, ch in enumerate(row):
            if ch != ".":
                for dy in range(k):
                    for dx in range(k):
                        yield x * k + dx, y * k + dy, ch
